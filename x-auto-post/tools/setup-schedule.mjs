async function updateSettings() {
  console.log("① 設定シートを更新中...");
  const rows = await readSheet(SETTINGS_SHEET);

  for (let i = 1; i < rows.length; i++) {
    const key = rows[i][0];
    if (key === "投稿時間") {
      await updateRange(SETTINGS_SHEET, `B${i + 1}`, [["12:00,21:00"]]);
      console.log(`  投稿時間 → 12:00,21:00 (行 ${i + 1})`);
    } else if (key === "投稿頻度") {
      await updateRange(SETTINGS_SHEET, `B${i + 1}`, [["2"]]);
      console.log(`  投稿頻度 → 2 (行 ${i + 1})`);
    }
  }
  console.log("  ✓ 設定シート更新完了");
}

async function registerPosts() {
  console.log("\n② 投稿管理シートに13件を登録中...");
  const existingRows = await readSheet(POST_SHEET);
  const ids = existingRows.slice(1).map((r) => parseInt(r[0], 10)).filter((n) => !isNaN(n));
  let nextId = ids.length > 0 ? Math.max(...ids) + 1 : 1;

  const newRows = POSTS.map((post) => [
    nextId++,
    "承認済み",
    post.scheduledAt,
    post.text,
    post.text.length,
    "",
    "",
    "",
  ]);

  await appendRows(POST_SHEET, newRows);
  console.log(`  ✓ ${newRows.length}件を登録しました`);
  newRows.forEach((r) => console.log(`    ID=${r[0]}  ${r[2]}  ${String(r[3]).slice(0, 20)}...`));
}

async function main() {
  console.log("=== x-auto-post スケジュール登録 ===\n");
  await updateSettings();
  await registerPosts();
  console.log("\n=== 完了 ===");
}

main().catch((err) => {
  console.error("Error:", err.message);
  process.exit(1);
});
